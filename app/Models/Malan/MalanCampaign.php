<?php

declare(strict_types=1);

namespace App\Models\Malan;

use App\Models\AiChatbot\ChatbotConversation;
use App\Models\AiChatbot\ChatbotInstance;
use App\Models\User;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Str;

class MalanCampaign extends Model
{
    public const STATUS_DRAFT = 'draft';

    public const STATUS_READY = 'ready';

    public const STATUS_RUNNING = 'running';

    public const STATUS_STOPPED = 'stopped';

    public const STATUS_COMPLETED = 'completed';

    protected $table = 'malan_campaigns';

    protected $fillable = [
        'chatbot_instance_id',
        'created_by_user_id',
        'name',
        'status',
        'is_active',
        'greenapi_url',
        'greenapi_webhook_token',
        'opening_message',
        'system_prompt',
        'excel_disk',
        'excel_path',
        'excel_original_name',
        'contacts_count',
        'messages_triggered_count',
        'responded_count',
        'leads_stored_count',
        'started_at',
        'stopped_at',
        'completed_at',
        'settings',
    ];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'is_active' => 'boolean',
            'contacts_count' => 'integer',
            'messages_triggered_count' => 'integer',
            'responded_count' => 'integer',
            'leads_stored_count' => 'integer',
            'started_at' => 'datetime',
            'stopped_at' => 'datetime',
            'completed_at' => 'datetime',
            'settings' => 'array',
        ];
    }

    protected static function booted(): void
    {
        static::creating(function (self $campaign): void {
            if (! is_string($campaign->greenapi_webhook_token) || $campaign->greenapi_webhook_token === '') {
                $campaign->greenapi_webhook_token = Str::random(48);
            }
            if ($campaign->is_active === null) {
                $campaign->is_active = true;
            }
        });
    }

    public function instance(): BelongsTo
    {
        return $this->belongsTo(ChatbotInstance::class, 'chatbot_instance_id');
    }

    public function creator(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by_user_id');
    }

    public function contacts(): HasMany
    {
        return $this->hasMany(MalanCampaignContact::class, 'campaign_id');
    }

    public function conversations(): HasMany
    {
        return $this->hasMany(ChatbotConversation::class, 'campaign_id');
    }

    public function isBotActive(): bool
    {
        return (bool) $this->is_active;
    }

    public function resolvedSystemPrompt(): string
    {
        $prompt = trim((string) ($this->system_prompt ?? ''));
        if ($prompt !== '') {
            return $prompt;
        }

        $instance = $this->relationLoaded('instance')
            ? $this->instance
            : $this->instance()->first();

        return self::defaultLeadSystemPrompt($instance instanceof ChatbotInstance ? $instance : null);
    }

    public static function defaultLeadSystemPrompt(?ChatbotInstance $instance = null): string
