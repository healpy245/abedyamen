        $parts = preg_split('/(?<=[.!?؟\n])\s*/u', $reply) ?: [$reply];
        $kept = [];
        foreach ($parts as $part) {
            $folded = $this->fold($part);
            if ($folded !== '' && preg_match(self::BACKING_OFF, $folded) === 1) {
                continue;
            }
            $kept[] = $part;
        }
        $result = trim(implode(' ', $kept));

        return $result === '' ? $reply : $result;
    }

    private function negates(string $folded): bool
    {
        return preg_match('/(?<!\p{L})(لا|مش|ما|بديش|مستحيل|ابدا)(?!\p{L})/u', $folded) === 1;
    }

    /**
     * The first objection whose cue appears and whose clip has not been sent yet.
     *
     * @param  list<string>  $sentMediaIds
     * @return array{id:string,party:string,clip:string,text:string}|null
     */
    public function match(string $text, bool $female, array $sentMediaIds, string $stage = '', array $answeredTopics = []): ?array
    {
        $folded = $this->fold($text);
        if ($folded === '') {
            return null;
        }
        foreach (self::OBJECTIONS as $objection) {
            if (isset($objection['stage']) && $objection['stage'] !== $stage) {
                continue;
            }
            if (in_array('اعتراض: '.$objection['id'], $answeredTopics, true)) {
                continue;
            }
            $hit = isset(self::ROOTS[$objection['id']]) && preg_match(self::ROOTS[$objection['id']], $folded) === 1;
            foreach ($hit ? [''] : $objection['cues'] as $cue) {
                if ($hit || $this->contains($folded, $this->fold($cue))) {
                    $text = $female ? ($objection['female'] ?? self::feminize($objection['male'])) : $objection['male'];
                    $clip = $objection['clip'];
                    if ($clip !== '' && in_array($clip, $sentMediaIds, true)) {
                        // Already sent: keep the argument, drop the clip and the line that points to it.
                        $clip = '';
                        $text = self::withoutClipLine($text);
                    }

                    return [
                        'id' => $objection['id'],
                        'party' => $objection['party'] ?? '',
                        'clip' => $clip,
                        'text' => $text,
                    ];
                }
            }
        }

        return null;
    }

    private function contains(string $haystack, string $cue): bool
    {
        if (str_contains($cue, ' ')) {
            return mb_strpos($haystack, $cue) !== false;
        }

        // Arabic clitics: "الديمقراطيين", "للمشتركه", "وبالموحده".
        return preg_match('/(?<!\p{L})(?:و|ف)?(?:ال|لل|بال|ل|ب)?'.preg_quote($cue, '/').'(?!\p{L})/u', $haystack) === 1;
    }

    private function fold(string $text): string
    {
        $text = mb_strtolower(trim($text));
        $text = (string) preg_replace('/\p{Mn}+/u', '', $text);
        $text = str_replace(['أ', 'إ', 'آ', 'ى', 'ة', 'ؤ', 'ئ', 'ـ'], ['ا', 'ا', 'ا', 'ي', 'ه', 'و', 'ي', ''], $text);
        $text = (string) preg_replace('/[^\p{L}\p{N}\s]+/u', ' ', $text);

        return trim((string) preg_replace('/\s+/u', ' ', $text));
    }
}
