    /**
     * A yes to the commitment question: "اكيد", "ان شاء الله", "اه رح اصوت".
     */
    public function commits(string $text): bool
    {
        $folded = $this->fold($text);
        if ($folded === '' || $this->negates($folded)) {
            return false;
        }
        // Fast typing repeats letters: "اا", "اههه", "اكييد" are still yes.
        $folded = (string) preg_replace('/(\p{L})\1+/u', '$1', $folded);
        $words = explode(' ', $folded);
        if (count($words) > 7) {
            return false;
        }
        $yes = ['ا', 'اه', 'اها', 'ايه', 'ايوه', 'ايوا', 'اي', 'نعم', 'اكيد', 'طبعا', 'تمام', 'ماشي', 'اوك', 'ok', 'yes', 'خلص', 'ان', 'شاء', 'الله', 'انشالله', 'انشاالله', 'انشاله', 'رح', 'بصوت', 'اصوت', 'بطلع', 'اطلع', 'للموحده', 'الموحده', 'موحده', 'بعطيها', 'صوتي', 'والله', 'يلا', 'مزبوط', 'صح', 'ناوي', 'ناويه', 'اله', 'لموحده'];
        foreach ($words as $word) {
            if (! in_array($word, $yes, true)) {
                return false;
            }
        }

        return true;
    }

