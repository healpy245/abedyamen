    /**
     * Fixed replies that make a case for الموحدة. Agreement right after one of
     * these is agreement with الموحدة; after anything else it is not.
     */
    public function isPitch(string $text): bool
    {
        $text = trim($text);
        if ($text === '') {
            return false;
        }
        // By content, not exact text: in real chats the model's own sentence goes in front of
        // the reply, so the message never equals the prepared text character for character.
        foreach (self::OBJECTIONS as $objection) {
            foreach ([$objection['male'], $objection['female'] ?? self::feminize($objection['male'])] as $body) {
                foreach (explode("\n", $body) as $line) {
                    if (mb_strlen($line) >= 40 && str_contains($text, $line)) {
                        return true;
                    }
                }
            }
        }

        return false;
    }

    /**
     * The campaign reply for a topic the model recognised, by id. Null when the
     * id is unknown or that reply already went out in this chat.
     *
     * @param  list<string>  $sentMediaIds
     * @param  list<string>  $answeredTopics
     * @return array{id:string,party:string,clip:string,text:string}|null
     */
    public function byId(string $id, bool $female, array $sentMediaIds, array $answeredTopics, string $ack = ''): ?array
    {
        if ($id === '' || in_array('اعتراض: '.$id, $answeredTopics, true)) {
            return null;
        }
        foreach (self::OBJECTIONS as $objection) {
            if ($objection['id'] !== $id) {
                continue;
            }
            $text = $female ? ($objection['female'] ?? self::feminize($objection['male'])) : $objection['male'];
            $clip = $objection['clip'];
            if ($clip !== '' && in_array($clip, $sentMediaIds, true)) {
                $clip = '';
                $text = self::withoutClipLine($text);
            }
            // The model's one sentence about what this person said goes first. It replaces the
            // reply's own first line only when that line is a short opener, never a line with facts.
            $ack = $this->cleanAck($ack);
            if ($ack !== '') {
                $lines = explode("\n", $text);
                if (mb_strlen($lines[0]) <= 60) {
                    $lines[0] = $ack;
                } else {
                    // Drop a short stock opener ("سؤال بمحلّه.") that would repeat the ack.
                    $lines[0] = (string) preg_replace('/^[^.،]{1,22}\.\s*/u', '', $lines[0]);
                    array_unshift($lines, $ack);
                }
                $text = implode("\n", $lines);
            }

            return [
                'id' => $objection['id'],
                'party' => $objection['party'] ?? '',
                'clip' => $clip,
                'text' => $text,
            ];
        }

        return null;
    }

