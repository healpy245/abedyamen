    /**
     * One sentence, at most 160 characters, and only if it does not back off or concede.
     */
    public function cleanAck(string $ack): string
    {
        $ack = trim($ack);
        if ($ack === '') {
            return '';
        }
        // First sentence only: concessions tend to come after a comma or a "بس".
        $first = preg_split('/(?<=[.!؟?])\s+/u', $ack)[0] ?? $ack;
        $first = trim((string) preg_replace('/[،,]\s*(بس|لكن|ومقارنه|ومقارنة|وللتوضيح)\b.*$/u', '.', $first));
        if ($first === '' || mb_strlen($first) > 160 || $this->backsOff($first)) {
            return '';
        }

        return $first;
    }

