    public static function corpus(): string
    {
        $parts = [];
        foreach (self::sections() as $section) {
            $parts[] = $section['title']."\n".$section['body'];
        }

        return implode("\n", $parts);
    }

    public static function retrieve(string $thread, string $topic = ''): string
    {
        $recent = mb_substr($thread, -500);
        $hits = self::match($recent, $topic);
        if ($hits === []) {
            $hits = self::match($thread, $topic);
        }
        $facts = DimaFacts::forThread($thread, $topic);
        if ($hits === [] && $facts === '') {
            return 'ما في مقطع دليل لهالرسالة. لا تجيبي رقم او تاريخ من عندك. اذا سال عن قانون او ميزانية او حزب، قولي انك بتحكي موقف القائمة فقط اذا هو مكتوب بالدليل.';
        }

        $lines = [];
        if ($facts !== '') {
            $lines[] = $facts;
        }
        if ($hits !== []) {
            $lines[] = 'المقاطع تحت من كراس كادر القائمة العربية الموحدة 2026 إلا اذا المقطع نفسه قال سجل برلماني. الكراس وثيقة حزبية مش تقرير مستقل. لا تضيف تاريخ او رقم مش مكتوب.';
            foreach ($hits as $section) {
                $lines[] = '['.$section['title'].'] '.$section['body'];
            }
        }

        return implode("\n", $lines);
    }

    /**
     * @return list<array{id:string,title:string,needles:list<string>,body:string}>
     */
    private static function match(string $haystack, string $topic): array
    {
        $hits = [];
        foreach (self::sections() as $section) {
            foreach ($section['needles'] as $needle) {
                if (($haystack !== '' && mb_stripos($haystack, $needle) !== false) || ($topic !== '' && mb_stripos($topic, $needle) !== false)) {
                    $hits[] = $section;
                    break;
                }
            }
        }

        return array_slice($hits, 0, 2);
    }
