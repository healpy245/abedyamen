    public static function arabic(?string $name): string
    {
        $name = self::clean($name);
        if ($name === '' || preg_match('/\p{Hebrew}/u', $name) !== 1) {
            return self::repair($name);
        }

        $words = [];
        foreach (explode(' ', $name) as $word) {
            $translated = self::word($word);
            if ($translated !== '') {
                $words[] = $translated;
            }
        }

        return self::stripTitles(self::joinArticle(trim(implode(' ', $words))));
    }

    /**
     * Fix a name that was already stored from the old letter-by-letter swap.
     */
    public static function repair(string $name): string
    {
        $name = self::clean($name);
        if ($name === '' || preg_match('/\p{Hebrew}/u', $name) === 1) {
            return $name;
        }
        $name = str_replace(['اللة', 'محيي أدين'], ['الله', 'محيي الدين'], $name);
        $parts = explode(' ', $name);
        foreach ($parts as $index => $part) {
            if (isset(self::REPAIR[$part])) {
                $parts[$index] = self::REPAIR[$part];
            }
        }

        return self::stripTitles(self::joinArticle(trim(implode(' ', $parts))));
    }

    private static function clean(?string $name): string
    {
        $name = str_replace(
            ["\u{200E}", "\u{200F}", "\u{202A}", "\u{202B}", "\u{202C}", "\u{202D}", "\u{202E}", "\u{2066}", "\u{2067}", "\u{2068}", "\u{2069}"],
            '',
            (string) $name,
        );
        $name = trim(preg_replace('/\s+/u', ' ', $name) ?? '');
        $name = preg_replace('/^\d+\.\s*/u', '', $name) ?? $name;
        $name = preg_replace('/^\d+\./u', '', $name) ?? $name;

        return trim($name);
    }

    /**
     * الشيخ and د. are titles in front of the person's name.
     */
    private static function stripTitles(string $name): string
    {
        $drop = ['الشيخ', 'شيخ', 'شيح'];
        $parts = [];
        foreach (explode(' ', $name) as $part) {
            $part = trim($part, "() \t");
            $part = preg_replace('/^د\./u', '', $part) ?? $part;
            if ($part === '' || $part === 'د' || in_array($part, $drop, true)) {
                continue;
            }
            $parts[] = $part;
        }

        return implode(' ', $parts);
    }

    /**
     * אל was stored as its own word, so "ال أطرش" should read الأطرش.
     */
    private static function joinArticle(string $name): string
    {
        $parts = explode(' ', $name);
        $out = [];
        $count = count($parts);
        for ($i = 0; $i < $count; $i++) {
            $part = $parts[$i];
            if (str_starts_with($part, 'الال')) {
                $part = mb_substr($part, 2);
            }
            if ($part === 'ال' && $i + 1 < $count) {
                $next = $parts[$i + 1];
                if (! str_starts_with($next, 'ال')) {
                    $parts[$i + 1] = 'ال'.$next;
                }
                continue;
            }
            $out[] = $part;
        }

        return implode(' ', $out);
    }

    private static function word(string $word): string
    {
        if (preg_match('/\p{Hebrew}/u', $word) !== 1) {
            return $word;
        }
        $word = str_replace(["\u{200F}", "\u{200E}", '’', '׳'], ['', '', "'", "'"], $word);
        if (isset(self::WORDS[$word])) {
            return self::WORDS[$word];
        }
        $word = self::normalize($word);
        if ($word === '') {
            return '';
        }
        if (isset(self::WORDS[$word])) {
            return self::WORDS[$word];
        }
        if (str_starts_with($word, 'אבו') && mb_strlen($word) > 3) {
            return 'أبو '.self::word(mb_substr($word, 3));
        }
        if (str_starts_with($word, 'אל') && mb_strlen($word) > 2) {
            $rest = mb_substr($word, 2);
            if (! str_starts_with($rest, 'י')) {
                $translated = self::word($rest);
                if ($translated === '') {
                    return '';
                }

                return 'ال'.$translated;
            }
        }

        return self::letters($word);
    }

    private static function normalize(string $word): string
    {
        $word = str_replace(
            ["ח'", "ע'", "צ'", "ת'", "ד'", "ג'"],
            ['خ', 'غ', 'ض', 'ث', 'ذ', 'ג'],
            $word,
        );
        $word = preg_replace('/ו{2,}/u', 'ו', $word) ?? $word;

        return preg_replace('/י{2,}/u', 'י', $word) ?? $word;
    }

    private static function letters(string $word): string
    {
        $word = preg_replace('/[\x{0591}-\x{05C7}]/u', '', $word) ?? $word;
        $map = [
            'א' => 'ا', 'ב' => 'ب', 'ג' => 'ج', 'ד' => 'د', 'ה' => 'ه', 'ו' => 'و', 'ז' => 'ز',
            'ח' => 'ح', 'ט' => 'ط', 'י' => 'ي', 'כ' => 'ك', 'ך' => 'ك', 'ל' => 'ل', 'מ' => 'م',
            'ם' => 'م', 'נ' => 'ن', 'ן' => 'ن', 'ס' => 'س', 'ע' => 'ع', 'פ' => 'ف', 'ף' => 'ف',
            'צ' => 'ص', 'ץ' => 'ص', 'ק' => 'ق', 'ר' => 'ر', 'ש' => 'ش', 'ת' => 'ت',
        ];
        $arabic = '';
        $length = mb_strlen($word);
        for ($i = 0; $i < $length; $i++) {
            $letter = mb_substr($word, $i, 1);
            $arabic .= $map[$letter] ?? $letter;
        }
        if (str_ends_with($arabic, 'اا')) {
            $arabic = mb_substr($arabic, 0, mb_strlen($arabic) - 2).'اء';
        }
        if (str_ends_with($arabic, 'الله')) {
            // الله keeps its ه. A final ه anywhere else is ة.
        } elseif (str_ends_with($arabic, 'ه') && mb_strlen($arabic) > 2) {
            $arabic = mb_substr($arabic, 0, mb_strlen($arabic) - 1).'ة';
        }
        if (str_starts_with($arabic, 'اي')) {
            $arabic = 'إ'.mb_substr($arabic, 1);
        } elseif (str_starts_with($arabic, 'او')) {
            $arabic = 'أ'.mb_substr($arabic, 1);
        } elseif (str_starts_with($arabic, 'ا')) {
            $arabic = 'أ'.mb_substr($arabic, 1);
        }

        return $arabic;
    }
