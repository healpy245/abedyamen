<?php

namespace Database\Seeders;

use App\Models\AiChatbot\ChatbotInstance;
use App\Models\User;
use Illuminate\Database\Seeder;

class SpeedComMelanChatbotInstanceSeeder extends Seeder
{
    public const INSTANCE_NAME = 'Melan Internet — SpeedCom';

    public function run(): void
    {
        $prompt = $this->systemPrompt();

        User::query()->each(function (User $user) use ($prompt): void {
            ChatbotInstance::query()->updateOrCreate(
                [
                    'user_id' => $user->id,
                    'name' => self::INSTANCE_NAME,
                ],
                [
                    'system_prompt' => $prompt,
                    'stores_members' => true,
                ]
            );
        });
    }

    protected function systemPrompt(): string
    {
        return <<<'PROMPT'
