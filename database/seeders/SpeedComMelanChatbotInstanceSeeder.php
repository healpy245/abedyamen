- كفرقاسم (الانطلاقة الأولى للشركة)
- كفربرا
- الطيبة
- الرملة
- قلنسوة
- عارة (قريبًا)
- عرعرة (قريبًا)

قريبًا سيتم الإعلان عن مناطق جديدة في الوسط العربي.

