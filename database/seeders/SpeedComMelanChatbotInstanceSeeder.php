- إذا واجه البوت صعوبة في الإجابة، يخبر الزبون: "هذه المعلومات المتوفرة لدي، سأطلب من مندوب أكثر خبرة التواصل معك."

## اللغات المدعومة
- العربية: الرد بالعربية عند التحدث بها.
